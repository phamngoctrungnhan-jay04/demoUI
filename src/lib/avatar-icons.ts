export const avatarIconRegistry = Object.fromEntries(
  iconList.map(([key, icon], index) => [
    key,
    { icon, color: colorCycle[index % colorCycle.length] },
  ]),
) as Record<string, { icon: LucideIcon; color: AvatarColor }>

export type AvatarIconKey = keyof typeof avatarIconRegistry

const fallbackAvatar = avatarIconRegistry.cat

/** avatarUrl từ backend là icon-key dạng string tự do (không ràng buộc enum ở DB) — phòng
 * trường hợp giá trị null/rỗng/không nằm trong registry (hồ sơ cũ, dữ liệu lạ). */
export function resolveAvatar(key: string | null | undefined) {
  if (key && key in avatarIconRegistry) return avatarIconRegistry[key as AvatarIconKey]
  return fallbackAvatar
}
